using DAL.Models.Administration;
using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace DAL.Models.Form
{
    public class NPF_FRM_Elements : BaseAuditModel, IAuditable
    {
        [Key]
        public long Id { get; set; }
        public int Order { get; set; }
        public long? ServiceId { get; set; }
        public string Name { get; set; }
        public string AdditionalLabel { get; set; } = string.Empty;
        [ForeignKey("InputTypeDetailId")]
        public virtual NPF_FRM_InputTypeDetails InputTypeDetails { get; set; }
        [ForeignKey("SourceId")]
        public virtual NPF_FRM_Source? Source { get; set; }
        [ForeignKey("UOMId")]
        public virtual NPF_SYS_UomHeader? UOM { get; set; }
        public bool Notification { get; set; } = false;
        public bool IsAdditional { get; set; } = false;

        public bool? IsMobileChecklist { get; set; } = false;
